// Bundles Monaco and Tinycast's page glue into Tinycast/Resources/MonacoEditor/.
//
//   pnpm install && node build.mjs
//
// The output is committed (like RaycastRuntime.generated.js) so building Tinycast never needs Node.
// The page is loaded from file://, where module scripts and workers are blocked, so everything is a
// single IIFE and Monaco falls back to running its worker on the main thread.

import { build } from "esbuild";
import { mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../Tinycast/Resources/MonacoEditor");
const monacoRoot = resolve(here, "node_modules/monaco-editor/esm/vs/editor");

// editor.main.js minus the css/html/json/typescript language services and the LSP client, which need
// workers and are not wanted in a file editor.
const mainImports = readFileSync(join(monacoRoot, "editor.main.js"), "utf8")
  .split("\n")
  .filter((line) => line.startsWith("import '") && !line.includes("/features/") && !line.includes("external/"))
  .map((line) => line.replace("import '", `import '${monacoRoot}/`).replace("'../../", "'"))
  .join("\n");
const entry = `${mainImports}\nimport '${monacoRoot}/editor.api.js';\nimport '${resolve(here, "src/main.js")}';\n`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const result = await build({
  stdin: { contents: entry, resolveDir: here, sourcefile: "entry.js", loader: "js" },
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["safari26"],
  minify: true,
  legalComments: "none",
  outdir: outDir,
  entryNames: "editor",
  loader: { ".ttf": "file", ".css": "css" },
  assetNames: "[name]",
  logLevel: "warning",
});

for (const warning of result.warnings) console.warn(warning.text);

writeFileSync(join(outDir, "index.html"), readFileSync(resolve(here, "src/index.html"), "utf8"));
writeFileSync(
  join(outDir, "README.txt"),
  "Generated by Scripts/monaco-bundle/build.mjs from monaco-editor (MIT). Do not edit.\n",
);

let total = 0;
for (const name of readdirSync(outDir)) {
  const size = statSync(join(outDir, name)).size;
  total += size;
  console.log(`${name}  ${(size / 1024).toFixed(0)} KB`);
}
console.log(`total  ${(total / 1024 / 1024).toFixed(2)} MB`);
